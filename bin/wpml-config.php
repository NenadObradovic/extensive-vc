<?php
/**
 * Generate wpml-config.xml from WPBakery Page Builder map of plugin elements
 *
 * Usage (from WordPress root with active plugin): wp eval-file <plugin path>/bin/wpml-config.php
 *
 * Text attributes are translated as text, link attributes with vc_link encoding and images as media ids,
 * shortcodes content (textarea_html) is translated by WPML by default.
 */

if ( ! defined( 'ABSPATH' ) || ! class_exists( 'WPBMap' ) ) {
	echo "WordPress with WPBakery Page Builder and Extensive VC plugin must be loaded\n";
	return;
}

// Text options which don't contain translatable text (sizes, colors, numbers, dates...)
$evc_wpml_excluded = '/(^|_)(class|size|sizes|width|height|margin|padding|spacing|color|speed|delay|duration|number|percent|percentage|value|values|digit|offset|thickness|radius|columns|font|weight|line_height|letter_spacing|date|hours|minutes|id|ids|position|start|max|min|space|zoom|level|step|data|top|bottom|left|right|link|url|email)($|_)/';
$evc_wpml_text     = '/(^|_)(title|text|label|labels|name|message|words|after|before|caption|description|subtitle|tagline|quote|author|content|legend|heading|features|currency|period|price)($|_)/';

$evc_wpml_shortcodes = array();

foreach ( WPBMap::getAllShortCodes() as $evc_base => $evc_map ) {
	if ( 0 !== strpos( $evc_base, 'evc_' ) || empty( $evc_map['params'] ) ) {
		continue;
	}

	$evc_attributes = array();

	foreach ( $evc_map['params'] as $evc_param ) {
		$evc_name = isset( $evc_param['param_name'] ) ? $evc_param['param_name'] : '';
		$evc_type = isset( $evc_param['type'] ) ? $evc_param['type'] : '';

		if ( '' === $evc_name || 'content' === $evc_name || 0 === strpos( $evc_name, 'evc_' ) ) {
			continue;
		}

		switch ( $evc_type ) {
			case 'vc_link':
				$evc_attributes[ $evc_name ] = 'type="link" encoding="vc_link"';
				break;
			case 'attach_image':
			case 'attach_images':
				$evc_attributes[ $evc_name ] = 'type="media-ids"';
				break;
			case 'textarea':
				$evc_attributes[ $evc_name ] = 'type="area"';
				break;
			case 'textfield':
				$evc_is_text = preg_match( $evc_wpml_text, $evc_name ) && ! preg_match( $evc_wpml_excluded, preg_replace( $evc_wpml_text, '', $evc_name ) ) || 0 === strpos( $evc_name, 'label_' ) || in_array( $evc_name, array( 'name', 'position', 'title', 'text', 'letter' ), true );

				if ( $evc_is_text ) {
					$evc_attributes[ $evc_name ] = '';
				}
				break;
		}
	}

	// Social profile links are not translated, team member position is job title
	if ( 'evc_team_member' === $evc_base ) {
		$evc_attributes = array_filter(
			$evc_attributes,
			function ( $key ) {
				return 0 !== strpos( $key, 'social_' );
			},
			ARRAY_FILTER_USE_KEY
		);
	}

	$evc_wpml_shortcodes[ $evc_base ] = $evc_attributes;
}

ksort( $evc_wpml_shortcodes );

$evc_xml  = "<wpml-config>\n";
$evc_xml .= "\t<!-- Generated by bin/wpml-config.php, translatable attributes of Extensive VC elements -->\n";
$evc_xml .= "\t<shortcodes>\n";

foreach ( $evc_wpml_shortcodes as $evc_base => $evc_attributes ) {
	$evc_xml .= "\t\t<shortcode>\n\t\t\t<tag>" . $evc_base . "</tag>\n";

	if ( ! empty( $evc_attributes ) ) {
		$evc_xml .= "\t\t\t<attributes>\n";

		foreach ( $evc_attributes as $evc_name => $evc_settings ) {
			$evc_xml .= "\t\t\t\t<attribute" . ( $evc_settings ? ' ' . $evc_settings : '' ) . '>' . $evc_name . "</attribute>\n";
		}

		$evc_xml .= "\t\t\t</attributes>\n";
	}

	$evc_xml .= "\t\t</shortcode>\n";
}

$evc_xml .= "\t</shortcodes>\n</wpml-config>\n";

file_put_contents( dirname( __DIR__ ) . '/wpml-config.xml', $evc_xml );

echo 'wpml-config.xml generated for ' . count( $evc_wpml_shortcodes ) . " elements\n";
